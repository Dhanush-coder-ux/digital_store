extension AppLocalizationExt on BuildContext {
  /// Reads a translated string reactively (rebuilds widget when language changes).
  String tr(String key, {Map<String, String>? args}) {
    final code = watch<LanguageProvider>().currentLocale.languageCode;
    return AppTranslations.translate(code, key, args: args);
  }

  /// Reads a translated string without subscribing to updates (safe inside callbacks).
  String trRead(String key, {Map<String, String>? args}) {
    final code = read<LanguageProvider>().currentLocale.languageCode;
    return AppTranslations.translate(code, key, args: args);
  }
}

